"""Offline, versioned CCP manufacturing recipes (raw quantities, not ME-adjusted)."""

import gzip
import hashlib
import json
from bisect import bisect_right
from datetime import date, datetime
from pathlib import Path


DATA = Path(__file__).with_name("data")
CATALOG = DATA / "killmail_recipe_history.json.gz"
MANIFEST = DATA / "killmail_recipe_history_manifest.json"
RUNTIME = Path.home() / "eveosint/data/market/recipe_history"


def canonical_json(value):
    return json.dumps(value, separators=(",", ":"), sort_keys=True).encode()


class RecipeHistory:
    """Exact snapshots for replay, or dated snapshots for loss-day valuation.

    Deltas retain material order, raw quantities and output yields. Loading a
    snapshot reconstructs the whole recipe set; current components are never
    silently mixed into a historical hull's manufacturing chain.
    """

    def __init__(self, catalog=CATALOG, manifest=MANIFEST, runtime_dir=RUNTIME):
        self.manifest = json.loads(Path(manifest).read_text())
        blob = Path(catalog).read_bytes()
        if self.manifest.get("format_version") != 1:
            raise ValueError("Unsupported recipe manifest format")
        if hashlib.sha256(blob).hexdigest() != self.manifest.get("catalog_sha256"):
            raise ValueError("Historical recipe catalog checksum mismatch")
        self.catalog = json.loads(gzip.decompress(blob))
        if self.catalog.get("format_version") != 1:
            raise ValueError("Unsupported recipe catalog format")
        self.versions = {row["version"]: row for row in self.manifest["snapshots"]}
        if len(self.versions) != len(self.manifest["snapshots"]):
            raise ValueError("Duplicate recipe versions")
        if [row["version"] for row in self.catalog["snapshots"]] != list(self.versions):
            raise ValueError("Recipe manifest and catalog versions differ")
        self.runtime_dir = Path(runtime_dir) if runtime_dir is not None else None
        self.runtime_versions = {}
        if self.runtime_dir is not None and (self.runtime_dir / "manifest.json").exists():
            runtime = json.loads((self.runtime_dir / "manifest.json").read_text())
            if runtime.get("format_version") != 1:
                raise ValueError("Unsupported runtime recipe history format")
            self.runtime_versions = {row["version"]: row for row in runtime["snapshots"]}
            if len(self.runtime_versions) != len(runtime["snapshots"]):
                raise ValueError("Duplicate imported recipe versions")
            for version, row in self.runtime_versions.items():
                if version in self.versions and row["recipes_sha256"] != self.versions[version]["recipes_sha256"]:
                    raise ValueError(f"Conflicting imported CCP recipe version: {version}")
            self.versions.update(self.runtime_versions)
        ordered = sorted(self.versions.values(), key=lambda row: (self._day(row), row["snapshot_date"]))
        self.days = [self._day(row) for row in ordered]
        self.dated_versions = [row["version"] for row in ordered]

    @staticmethod
    def _day(row):
        return date.fromisoformat(row.get("effective_from", row["snapshot_date"])[:10])

    def version_on(self, day):
        """Latest recorded recipe effective on a UTC day, never a future SDE."""
        if isinstance(day, datetime):
            raise ValueError("Pass a UTC calendar date to recipe selection")
        index = bisect_right(self.days, day) - 1
        return self.dated_versions[index] if index >= 0 else None

    def resolve(self, version):
        # ISO dates are exact aliases for dated legacy SDEs, not an as-of
        # search through sparse snapshots. Native SDEs use their build ID.
        if len(version) == 10 and version[4] == "-" and version[7] == "-":
            version = version.replace("-", "")
        if version not in self.versions:
            raise ValueError(
                f"Unknown historical recipe version {version!r}; "
                "use --list-recipe-versions to list exact snapshots"
            )
        return version

    def recipes(self, version):
        version = self.resolve(version)
        if version in self.runtime_versions:
            expected = self.runtime_versions[version]
            # Only content-addressed names generated by record_snapshot.
            path = self.runtime_dir / (expected["recipes_sha256"] + ".json.gz")
            recipes = json.loads(gzip.decompress(path.read_bytes()))
            self._verify(recipes, expected)
            return recipes
        recipes = {}
        for snapshot in self.catalog["snapshots"]:
            for type_id in snapshot["remove"]:
                recipes.pop(str(type_id), None)
            for type_id, output, materials in snapshot["upsert"]:
                recipes[str(type_id)] = [output, materials]
            if snapshot["version"] == version:
                expected = self.versions[version]
                self._verify(recipes, expected)
                return recipes
        raise ValueError(f"Historical recipe version missing from catalog: {version}")

    @staticmethod
    def _verify(recipes, expected):
        if (len(recipes) != expected["recipe_count"] or
                hashlib.sha256(canonical_json(recipes)).hexdigest() != expected["recipes_sha256"]):
            raise ValueError(f"Historical recipes checksum mismatch: {expected['version']}")

    def blueprint_rows(self, version):
        yield from blueprint_rows(self.recipes(version))


def blueprint_rows(recipes):
    for type_id, (output, materials) in recipes.items():
        yield {"activities": {"manufacturing": {
            "products": [{"typeID": int(type_id), "quantity": output}],
            "materials": [{"typeID": material, "quantity": quantity}
                          for material, quantity in materials],
        }}}


def raw_recipes(rows):
    recipes = {}
    for row in rows:
        activities = row.get("activities", {})
        manufacture = activities.get("manufacturing") or activities.get("1") or {}
        products, materials = manufacture.get("products", []), manufacture.get("materials", [])
        if not products or not materials:
            continue
        product = products[0]
        type_id = product.get("productTypeID", product.get("typeID"))
        if type_id is not None:
            recipes[str(type_id)] = [product.get("quantity", 1), [
                [m.get("materialTypeID", m.get("typeID")), m["quantity"]] for m in materials
            ]]
    return recipes


def record_snapshot(version, released, rows, source, directory=RUNTIME):
    """Keep imported CCP recipes for later losses, atomically and deduplicated."""
    # Validate dates before recording metadata used by automatic selection.
    date.fromisoformat(released[:10])
    recipes = raw_recipes(rows)
    if not recipes:
        raise ValueError("Cannot record an empty manufacturing recipe set")
    payload = canonical_json(recipes)
    digest = hashlib.sha256(payload).hexdigest()
    directory = Path(directory)
    directory.mkdir(parents=True, exist_ok=True)
    path = directory / (digest + ".json.gz")
    if not path.exists():
        temporary = path.with_suffix(".tmp")
        temporary.write_bytes(gzip.compress(payload, mtime=0))
        temporary.replace(path)
    manifest_path = directory / "manifest.json"
    manifest = json.loads(manifest_path.read_text()) if manifest_path.exists() else {"format_version": 1, "snapshots": []}
    if manifest.get("format_version") != 1:
        raise ValueError("Unsupported runtime recipe history format")
    metadata = dict(version=version, snapshot_date=released, effective_from=released[:10],
                    date_kind="ccp_release_timestamp", source=source,
                    recipes_sha256=digest, recipe_count=len(recipes))
    existing = next((row for row in manifest["snapshots"] if row["version"] == version), None)
    if existing is not None:
        if existing != metadata:
            raise ValueError(f"Imported recipe version changed: {version}")
        return metadata
    manifest["snapshots"].append(metadata)
    manifest["snapshots"].sort(key=lambda row: row["snapshot_date"])
    temporary = manifest_path.with_suffix(".tmp")
    temporary.write_text(json.dumps(manifest, indent=2) + "\n")
    temporary.replace(manifest_path)
    return metadata
